    function readJSON(key, fallback) {
        try { return JSON.parse(localStorage.getItem(key) || "") || fallback; }
        catch (error) { return fallback; }
    }

    function money(value) { return "RM" + Number(value || 0).toFixed(2); }
    function text(ms, en) { return language === "en" ? en : ms; }

    const reverseTranslations = Object.keys(translations).reduce(function (result, malay) {
        if (!result[translations[malay]]) result[translations[malay]] = malay;
        return result;
    }, {});

    function translateDynamic(value) {
        const source = String(value == null ? "" : value).trim();
        if (!source) return source;
        if (translations[source]) return translations[source];

        let match = source.match(/^(\d+) unit$/i);
        if (match) return match[1] + " units";
        match = source.match(/^(\d+) set$/i);
        if (match) return match[1] + " sets";
        match = source.match(/^Tingkatan (\d+)(?: \((Lelaki|Perempuan)\))?$/i);
        if (match) return "Form " + match[1] + (match[2] ? " (" + (match[2].toLowerCase() === "lelaki" ? "Male" : "Female") + ")" : "");
        match = source.match(/^Tingkatan (\d+) — pilih jantina$/i);
        if (match) return "Form " + match[1] + " — choose gender";
        match = source.match(/^Panduan Saiz - (.+)$/i);
        if (match) return "Size Guide - " + translateDynamic(match[1]);
        match = source.match(/^Pakej wajib: (RM[\d.]+)$/i);
        if (match) return "Required package: " + match[1];
        match = source.match(/^(.+) Subjumlah:$/i);
        if (match) return translateDynamic(match[1]) + " Subtotal:";
        match = source.match(/^Rujukan: (.+)$/i);
        if (match) return "Reference: " + match[1];
        match = source.match(/^Draf pesanan disimpan automatik pada (.+)\.$/i);
        if (match) return "Order draft saved automatically at " + match[1] + ".";
        match = source.match(/^Anda telah log masuk sebagai (.+) \((.+)\)\.$/i);
        if (match) return "You are logged in as " + match[1] + " (" + match[2] + ").";
        match = source.match(/^(XS|S|M|L|XL|XXL|XXXL|XXXXL) - (Tersedia|Stok Rendah|Kehabisan Stok)$/i);
        if (match) return match[1] + " - " + translations[match[2]];
        return source;
    }

    function translateMessage(value) {
        let output = translateDynamic(value);
        if (output !== value) return output;
        const replacements = [
            ["Pesanan berjaya dihantar!", "Order submitted successfully!"],
            ["ID Pesanan:", "Order ID:"],
            ["Jumlah Pembayaran:", "Payment Total:"],
            ["Status: Pembayaran Sedang Disahkan", "Status: Payment Under Verification"],
            ["Item wajib tidak boleh dibuang:", "Required item cannot be removed:"],
            ["Sila masukkan kuantiti add-on yang sah untuk", "Please enter a valid add-on quantity for"],
            ["Sila pilih saiz untuk", "Please choose a size for"],
            [" dalam Tingkatan ", " in Form "],
            ["Pengguna", "User"]
        ];
        replacements.forEach(function (entry) { output = output.split(entry[0]).join(entry[1]); });
        Object.keys(translations).forEach(function (malay) {
            if (/^(Buku|T-Shirt|Seluar|Tali Leher|Lencana|Tanda Nama|Saham Koperasi|Wooven Beg|Sketch Pad)/.test(malay)) {
                output = output.split(malay).join(translations[malay]);
            }
        });
        return output;
    }

    function escapeHTML(value) {
        return String(value == null ? "" : value)
            .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
            .replace(/"/g, "&quot;").replace(/'/g, "&#039;");
    }

