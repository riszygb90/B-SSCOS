    function translateTextNode(node) {
        const parent = node && node.parentElement;
        if (!parent || /^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA)$/i.test(parent.tagName)) return;
        const rawValue = node.nodeValue;
        const current = rawValue.trim().replace(/\s+/g, " ");
        if (!current) return;

        if (!node.__bsscosMalay || (node.__bsscosLastRendered && current !== node.__bsscosLastRendered)) {
            if (translations[current] || translateDynamic(current) !== current) node.__bsscosMalay = current;
            else if (reverseTranslations[current]) node.__bsscosMalay = reverseTranslations[current];
            else node.__bsscosMalay = "";
        }

        if (!node.__bsscosMalay) return;
        const replacement = language === "en" ? translateDynamic(node.__bsscosMalay) : node.__bsscosMalay;
        if (replacement !== current) {
            const leading = (rawValue.match(/^\s*/) || [""])[0];
            const trailing = (rawValue.match(/\s*$/) || [""])[0];
            node.nodeValue = leading + replacement + trailing;
        }
        node.__bsscosLastRendered = replacement;
    }

    function translateAttributes(element) {
        if (!element || !element.getAttribute) return;
        ["placeholder", "aria-label", "title", "alt"].forEach(function (name) {
            const current = element.getAttribute(name);
            if (!current) return;
            element.__bsscosMalayAttributes = element.__bsscosMalayAttributes || {};
            const stored = element.__bsscosMalayAttributes[name];
            const last = element.__bsscosRenderedAttributes && element.__bsscosRenderedAttributes[name];
            if (!stored || (last && current !== last)) {
                if (attributeTranslations[current]) element.__bsscosMalayAttributes[name] = current;
                else if (reverseTranslations[current]) element.__bsscosMalayAttributes[name] = reverseTranslations[current];
            }
            const malay = element.__bsscosMalayAttributes[name];
            if (!malay) return;
            const rendered = language === "en" ? (attributeTranslations[malay] || translations[malay] || malay) : malay;
            element.setAttribute(name, rendered);
            element.__bsscosRenderedAttributes = element.__bsscosRenderedAttributes || {};
            element.__bsscosRenderedAttributes[name] = rendered;
        });
    }

    function translateTree(root) {
        if (!root || translating) return;
        translating = true;
        const nodes = [];
        if (root.nodeType === Node.TEXT_NODE) nodes.push(root);
        else {
            const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
            while (walker.nextNode()) nodes.push(walker.currentNode);
        }
        nodes.forEach(translateTextNode);

        if (root.nodeType === Node.ELEMENT_NODE) translateAttributes(root);
        if (root.querySelectorAll) root.querySelectorAll("[placeholder], [aria-label], [title], [alt]").forEach(translateAttributes);
        translating = false;
    }

    function setLanguage(next) {
        language = next === "en" ? "en" : "ms";
        localStorage.setItem(LANGUAGE_KEY, language);
        document.documentElement.lang = language === "en" ? "en" : "ms";
        updateLanguageSwitch();
        translateTree(document.body);
        if (!document.__bsscosMalayTitle) document.__bsscosMalayTitle = reverseTranslations[document.title] || document.title;
        document.title = language === "en" ? (translations[document.__bsscosMalayTitle] || document.__bsscosMalayTitle) : document.__bsscosMalayTitle;
        document.dispatchEvent(new CustomEvent("bsscos-language-change", { detail: { language: language } }));
    }

